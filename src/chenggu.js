const CN = '〇一二三四五六七八九';
export const fmtWeight = (q) => {
  const liang = Math.floor(q / 10), qian = q % 10;
  if (!liang) return `${CN[qian]}錢`;
  return `${CN[liang]}兩${qian ? CN[qian] + '錢' : ''}`;
};

// yearGz: 農曆年干支；lunarMonth: 1-12；lunarDay: 1-30；hourZhi: 時辰地支或 null
export function chengGu(yearGz, lunarMonth, lunarDay, hourZhi) {
  const parts = [
    { label: `年（${yearGz}）`, v: YEAR[yearGz] },
    { label: `月（${lunarMonth} 月）`, v: MONTH[lunarMonth - 1] },
    { label: `日（${lunarDay} 日）`, v: DAY[lunarDay - 1] },
  ];
  if (hourZhi) parts.push({ label: `時（${hourZhi}時）`, v: HOUR[hourZhi] });
  const total = parts.reduce((s, p) => s + p.v, 0);
  return {
    parts: parts.map((p) => ({ ...p, text: fmtWeight(p.v) })),
    total, text: fmtWeight(total),
    song: hourZhi ? SONG[total] || '' : '',
    complete: !!hourZhi,
  };
}
